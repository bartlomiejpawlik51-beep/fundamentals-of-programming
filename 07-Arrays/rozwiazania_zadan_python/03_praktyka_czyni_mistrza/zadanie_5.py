# Obliczanie drugiej potęgi każdego elementu

arr = [8, 2, 5, 1, 9]

print("Array:", end=" ")
for value in arr:
    print(value, end=" ")

print()
print("2nd power:", end=" ")
for value in arr:
    print(value * value, end=" ")
print()
