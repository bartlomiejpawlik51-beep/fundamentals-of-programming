# Polecenie: Użyj modułu math, aby obliczyć pierwiastek kwadratowy z 7,
# logarytm naturalny liczby 5 oraz sinus kąta 90 stopni.

import math

print("Pierwiastek z 7:", math.sqrt(7))
print("Logarytm naturalny z 5:", math.log(5))

# Funkcja sin() przyjmuje kąt w radianach, dlatego zamieniamy 90 stopni na radiany.
angle = math.radians(90)
print("Sinus 90 stopni:", math.sin(angle))
